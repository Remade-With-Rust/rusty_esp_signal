/// The per-slot transmit words the blob writes on its FIRST transmit, and
/// not before: at bring-up this whole block reads zero (only four of the
/// `+0x04` words are set), and the first frame out brings all 54 of these
/// into being at once. They do not move again -- nine beacons of five
/// different lengths changed not one bit of them -- so this is a one-time
/// arming of the transmit path, not per-frame configuration. Observed on
/// silicon (E5's P4, 2026-10-08) by watching `0x600a5000`..`0x600a5400`
/// across a beacon run of `c6-s1-link`.
///
/// Nine entries, six words each, at a stride of 0x74: `+0x04`, `+0x24`,
/// `+0x28`, `+0x2c`, `+0x30`, `+0x34`. The entries are uniform but for
