/// The modem subsystem BEYOND the MAC, where replaying the MAC's whole
/// block proved the answer is not. From unfiltered two-pass dumps of
/// `0x600a6000`..`0x600b0000` on both stacks (E5's P4, 2026-10-08), with
/// three classes of noise discarded: the two windows of uninitialised SRAM
/// (`0x600a6000`..`0x600a6400` reads stable pseudo-random content under
/// BOTH stacks), the analog I2C master's command memory
/// (`0x600af800`..`0x600b0000`, the PHY's calibration, different every
/// boot), and the 24 words that moved between the two passes.
///
/// What is left is five settings. The first three are registers the blob
/// sets and ours leaves entirely at ZERO; the last two differ by a single
/// bit each.
