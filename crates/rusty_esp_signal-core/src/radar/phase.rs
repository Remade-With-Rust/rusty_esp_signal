/// Thresholds for a [`PhaseDetector`], in parts per million of circular
/// variance.
///
/// Its own type and not [`super::csi::Config`], whose fields are named for
/// permille: a threshold that reads `on_permille: 450` and means ppm is a
/// bug waiting for a reader.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PhaseConfig {
    /// Phase wander (ppm) at or above which the verdict switches to present.
    pub on_ppm: u32,
    /// Phase wander (ppm) at or below which it may switch back to absent.
    pub off_ppm: u32,
    /// Minimum time the verdict stays present after the last frame above
    /// `on_ppm`.
    pub hold: Micros,
}

impl Default for PhaseConfig {
    /// Set from the same two ESP32-C6 captures as the amplitude defaults
    /// and by the same rule -- `on` at 1.5 × the empty room's ceiling,
    /// `off` just above the ceiling -- with the numbers in `docs/LEDGER.md`.
    /// A product calibrates per room from [`PhaseDetector::wander`].
    fn default() -> Self {
        PhaseConfig {
            on_ppm: 380,
            off_ppm: 260,
            hold: Micros::from_secs(3),
        }
    }
}

