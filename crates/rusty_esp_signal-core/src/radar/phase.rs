/// The unit-vector scale of [`SIN_QUARTER`] and of every cosine and sine
/// this module carries.
const UNIT: i32 = 16384;

/// The angle of `(x, y)` in binary radians: `0` along `+x`, `16384` along
/// `+y`, wrapping at a full turn.
///
/// One octant from the table, the rest by symmetry. Both inputs are meant
/// to be small (an ESP32 CSI entry is two `i8`s), but any `i32` works: the
/// ratio is formed as `min * 256 / max`, which cannot overflow for
/// `|v| < 2^23`, and every raw CSI value is inside that by a factor of
/// sixty thousand.
#[must_use]
pub const fn atan2_brad(y: i32, x: i32) -> i16 {
    if x == 0 && y == 0 {
        return 0;
    }
    let ax = x.unsigned_abs();
    let ay = y.unsigned_abs();
    // Within the first octant the table answers directly; in the second the
    // angle is a quarter turn minus the table of the inverse ratio.
    let a: i32 = if ay <= ax {
        ATAN_OCTANT[(ay * 256 / ax) as usize] as i32
    } else {
        16384 - ATAN_OCTANT[(ax * 256 / ay) as usize] as i32
    };
    let a = if x < 0 { 32768 - a } else { a };
    let a = if y < 0 { -a } else { a };
    // 32768 (exactly half a turn) wraps to i16::MIN, which is the same angle.
    a as i16
}

/// `a / b` rounded to nearest, for `b > 0`. Integer `/` truncates toward
/// zero, which for a mean vector is a bias with a sign.
const fn div_round(a: i32, b: i32) -> i32 {
    if a >= 0 {
        (a + b / 2) / b
    } else {
        -((-a + b / 2) / b)
    }
}

/// `(cos, sin)` of a binary-radian angle, each scaled to [`UNIT`].
#[must_use]
const fn unit_vector(angle: i16) -> (i32, i32) {
    // 1024 steps around the circle: the top two bits of the angle are the
    // quadrant, the next eight index the quarter-wave table.
    let a = (angle as u16) >> 6; // 0..1024
    let quadrant = a >> 8;
    let i = (a & 255) as usize;
    let s = SIN_QUARTER[i] as i32;
    let c = SIN_QUARTER[256 - i] as i32;
    match quadrant {
        0 => (c, s),
        1 => (-s, c),
        2 => (-c, -s),
        _ => (s, -c),
    }
}

/// Per-frame sanitised phase, one binary-radian angle per valid subcarrier.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Phases {
    /// The residual phase after the per-frame line is removed, in layout
    /// order; only the first `count` entries are meaningful.
    pub phase: [i16; MAX_SUBCARRIERS],
    /// Valid subcarriers in `phase`.
    pub count: u8,
}

impl Phases {
    /// The valid phases.
    #[must_use]
    pub fn phases(&self) -> &[i16] {
        &self.phase[..self.count as usize]
    }
}

impl CsiFrame<'_> {
    /// Sanitised phase per valid subcarrier of `layout`.
    ///
    /// The raw angles are unwrapped across the subcarriers (the shortest arc
    /// between neighbours, which `wrapping_sub` on binary radians is), then
    /// the least-squares line through them -- the per-frame carrier offset
    /// and sampling-time slope -- is subtracted. What remains is the
    /// channel's own shape, comparable frame to frame.
    ///
    /// `InvalidGeometry` when the buffer is shorter than the layout needs,
    /// or the layout has fewer than two subcarriers (a line needs two
    /// points).
    pub fn phases(&self, layout: &Layout) -> Result<Phases> {
        if self.iq.len() < 2 * layout.entries || layout.count() > MAX_SUBCARRIERS {
            return Err(Error::InvalidGeometry);
        }
        // Raw angles, then unwrapped: `u[k]` is the cumulative shortest-arc
        // walk from `u[0]`, an i32 because it may leave the i16 circle.
        let mut u = [0i32; MAX_SUBCARRIERS];
        let mut n = 0usize;
        let mut prev: i16 = 0;
        for r in layout.valid {
            if r.start >= r.end {
                continue;
            }
            for p in self.iq[2 * r.start..2 * r.end].chunks_exact(2) {
                let im = i32::from(p[0]);
                let re = i32::from(p[1]);
                let raw = atan2_brad(im, re);
                u[n] = if n == 0 {
                    i32::from(raw)
                } else {
                    u[n - 1] + i32::from(raw.wrapping_sub(prev))
                };
                prev = raw;
                n += 1;
            }
        }
        if n < 2 {
            return Err(Error::InvalidGeometry);
        }
        // Least squares over k = 0..n: slope = (n·Σku − Σk·Σu) / (n·Σk² − (Σk)²),
        // intercept = (Σu − slope·Σk) / n. Both in Q16 so the residual keeps
        // sixteen fractional bits until the final shift. `n ≤ 64` and
        // `|u| < 64 · 2^15`, so every product is well inside i64.
        let nn = n as i64;
        let sk: i64 = nn * (nn - 1) / 2;
        let skk: i64 = (nn - 1) * nn * (2 * nn - 1) / 6;
        let mut su: i64 = 0;
        let mut sku: i64 = 0;
        for (k, &v) in u[..n].iter().enumerate() {
            su += i64::from(v);
            sku += k as i64 * i64::from(v);
        }
        let den = nn * skk - sk * sk; // > 0 for n ≥ 2
        let slope_q16 = ((nn * sku - sk * su) << 16) / den;
        let icpt_q16 = ((su << 16) - slope_q16 * sk) / nn;

        let mut out = Phases {
            phase: [0; MAX_SUBCARRIERS],
            count: n as u8,
        };
        for (k, &v) in u[..n].iter().enumerate() {
            let resid_q16 = (i64::from(v) << 16) - slope_q16 * k as i64 - icpt_q16;
            // Back to whole binary radians, then onto the circle. The
            // arithmetic shift rounds toward −∞ uniformly, which a wrap does
            // not care about.
            out.phase[k] = (resid_q16 >> 16) as i16;
        }
        Ok(out)
    }
}

/// Presence from the circular variance of the sanitised phase over the last
/// `W` frames.
///
/// Same shape as [`super::csi::PresenceDetector`]: a ring, sums carried by
/// the one frame that changes, one verdict with hysteresis. The statistic
/// differs -- circular variance instead of a coefficient of variation --
/// because the quantity is an angle.
pub struct PhaseDetector<const W: usize> {
    config: PhaseConfig,
    ring: [[i16; MAX_SUBCARRIERS]; W],
    /// `Σ cos`, `Σ sin` over the ring per subcarrier, in [`UNIT`]s.
    ///
    /// The invariant is `sum == Σ unit_vector(ring[f][sc])` over every slot,
    /// FILLED OR NOT. A zeroed ring is `W` copies of angle 0, whose unit
    /// vector is `(UNIT, 0)` and not `(0, 0)` -- so the sums start at
    /// `(W · UNIT, 0)`. Started at zero, every push into a never-filled slot
    /// subtracted a phantom `(UNIT, 0)`, and the same frame pushed `W` times
    /// read 883 ‰ of variance instead of none. The amplitude detector has no
    /// such trap: an amplitude of 0 contributes 0.
    sum_cos: [i32; MAX_SUBCARRIERS],
    sum_sin: [i32; MAX_SUBCARRIERS],
    count: u8,
    filled: usize,
    next: usize,
    /// Parts per million.
    wander: u32,
    present: bool,
    last_motion: Micros,
    frames: u32,
}

impl<const W: usize> core::fmt::Debug for PhaseDetector<W> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("PhaseDetector")
            .field("window", &W)
            .field("filled", &self.filled)
            .field("wander", &self.wander)
            .field("present", &self.present)
            .field("frames", &self.frames)
            .finish_non_exhaustive()
    }
}

impl<const W: usize> PhaseDetector<W> {
    /// `W` unit vectors of magnitude [`UNIT`] must sum inside an `i32`:
    /// `W · 2^14 < 2^31`, i.e. `W < 2^17`, stated to the compiler.
    const W_FITS_I32_SUM: () = assert!(W < 1 << 17);

    /// A detector with `config`.
    #[must_use]
    pub const fn new(config: PhaseConfig) -> Self {
        PhaseDetector {
            config,
            ring: [[0; MAX_SUBCARRIERS]; W],
            // A zeroed ring is W angles of 0: see the field's note.
            sum_cos: [W as i32 * UNIT; MAX_SUBCARRIERS],
            sum_sin: [0; MAX_SUBCARRIERS],
            count: 0,
            filled: 0,
            next: 0,
            wander: 0,
            present: false,
            last_motion: Micros::ZERO,
            frames: 0,
        }
    }

    /// The thresholds in use.
    #[must_use]
    pub const fn config(&self) -> &PhaseConfig {
        &self.config
    }

    /// Replace the thresholds (calibration) without dropping the window.
    pub fn set_config(&mut self, config: PhaseConfig) {
        self.config = config;
    }

    /// The last computed phase wander, **parts per million**: mean over
    /// subcarriers of `1 000 000 · (1 − |mean unit vector|)` across the
    /// window. The number to log while calibrating a room.
    #[must_use]
    pub const fn wander(&self) -> u32 {
        self.wander
    }

    /// Frames pushed so far.
    #[must_use]
    pub const fn frames(&self) -> u32 {
        self.frames
    }

    /// True once the window holds `W` frames.
    #[must_use]
    pub const fn warm(&self) -> bool {
        self.filled >= W
    }

    /// Forget the window (after a channel change, for instance).
    ///
    /// The ring and the sums are left alone, exactly as the amplitude
    /// detector leaves them: the invariant `sum == Σ ring` must survive a
    /// reset, and it does because neither side is touched.
    pub fn reset(&mut self) {
        self.filled = 0;
        self.next = 0;
        self.count = 0;
        self.wander = 0;
        self.present = false;
    }

    /// Push one frame's sanitised phases taken at `now` and get the verdict.
    pub fn push(&mut self, phases: &Phases, now: Micros) -> Verdict {
        if phases.count == 0 {
            return self.verdict_now();
        }
        if self.filled > 0 && phases.count != self.count {
            self.reset();
        }
        self.count = phases.count;
        let () = Self::W_FITS_I32_SUM;
        // Carry the sums from the one frame that changes: subtract the unit
        // vector of the angle leaving the slot, add the one arriving.
        let new = phases.phases();
        let slot = &mut self.ring[self.next];
        for (sc, (&angle, old)) in new.iter().zip(slot[..new.len()].iter_mut()).enumerate() {
            let (oc, os) = unit_vector(*old);
            let (nc, ns) = unit_vector(angle);
            self.sum_cos[sc] = self.sum_cos[sc] - oc + nc;
            self.sum_sin[sc] = self.sum_sin[sc] - os + ns;
            *old = angle;
        }
        self.next = (self.next + 1) % W;
        if self.filled < W {
            self.filled += 1;
        }
        self.frames = self.frames.wrapping_add(1);
        if self.filled < W {
            return Verdict::Warming;
        }
        self.wander = self.compute_wander();
        if self.wander >= self.config.on_ppm {
            self.present = true;
            self.last_motion = now;
        } else if self.present
            && self.wander <= self.config.off_ppm
            && now.0.saturating_sub(self.last_motion.0) >= self.config.hold.0
        {
            self.present = false;
        }
        self.verdict_now()
    }

    /// `motion` is the wander in **tens of ppm**, clipped to a byte: a walk
    /// on the ledger's captures reads 30–150, a scrambled channel 255.
    const fn verdict_now(&self) -> Verdict {
        if self.filled < W {
            Verdict::Warming
        } else if self.present {
            let tens = self.wander / 10;
            Verdict::Present {
                motion: if tens > 255 { 255 } else { tens as u8 },
            }
        } else {
            Verdict::Absent
        }
    }

    /// Mean over subcarriers of `1 000 000 · (1 − R)`, where `R` is the
    /// length of the mean unit vector over the window for one subcarrier.
    fn compute_wander(&self) -> u32 {
        let n = (self.count as usize).min(MAX_SUBCARRIERS);
        if n == 0 || W == 0 {
            return 0;
        }
        let w = W as i32;
        let mut total: u32 = 0;
        for sc in 0..n {
            // The mean unit vector, each component in −UNIT..=UNIT, so its
            // length is at most UNIT·√2 and the squares fit u32 easily.
            // ROUNDED, not truncated. Every floor here lands on the same
            // side: a shorter mean vector is more variance. Truncating the
            // components and the square root together read a constant
            // +61 ppm above the float replica -- exactly one unit of 2^14 --
            // on both captures, with no scatter. Rounding the division to
            // nearest and taking `isqrt` at double resolution removes it.
            let mc = div_round(self.sum_cos[sc], w);
            let ms = div_round(self.sum_sin[sc], w);
            // |mc|, |ms| ≤ 2^14 (a unit vector to ±1), so mc² + ms² ≤ 2^29
            // and, CAST FIRST, 4× that is 2^31: inside u32, past i32.
            let sq = (mc * mc + ms * ms) as u32;
            let r = (isqrt(4 * sq) as i32 + 1) / 2;
            let r = if r > UNIT { UNIT } else { r };
            // ppm of variance: (UNIT − r) · 10^6 / 2^14, and 10^6 / 2^14 is
            // exactly 15 625 / 256. So one u32 multiply and a shift, exact,
            // where `1_000_000 * (UNIT - r)` is 1.6 × 10^10 at a scrambled
            // channel and overflowed i32 -- caught by the unit test that
            // scrambles one, and only there: a real room never gets past a
            // few thousand. At most 2.56 × 10^8 per subcarrier, 64 of them.
            let d = (UNIT - r) as u32;
            total += (d * 15_625) >> 8;
        }
        total / n as u32
    }
}

