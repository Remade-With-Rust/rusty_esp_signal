//! The phase half of Wi-Fi channel state, beside the amplitude half in
//! [`super::csi`].
//!
//! A CSI entry is a complex number per subcarrier: [`super::csi`] keeps its
//! magnitude and discards its angle. The angle carries the same motion
//! signal from a different direction -- a body changes the path lengths, and
//! path length is phase -- and it is what every phase-based presence method
//! (and RuView's no-model fallback) measures. This module measures it in
//! fixed point, on the same raw buffer, with nothing new captured.
//!
//! # Binary radians, because the wrap is the point
//!
//! Every angle here is an `i16` in **binary radians**: 65 536 is one turn,
//! so `i16::MIN..=i16::MAX` is one full circle and wrapping arithmetic *is*
//! circular arithmetic. The difference between two neighbouring
//! subcarriers' phases, computed with `wrapping_sub`, is the shortest arc
//! between them -- which is exactly the unwrap step that phase sanitisation
//! needs, for free, with no branch and no `2π` anywhere.
//!
//! # The pipeline, one frame at a time
//!
//! 1. `atan2` per valid subcarrier, from a 257-entry table over one octant
//!    ([`atan2_brad`]; error under 0.15 degrees, measured in the tests).
//! 2. **Sanitise.** Raw CSI phase carries two artefacts that have nothing to
//!    do with the room: a constant offset per frame (carrier frequency
//!    offset) and a slope across subcarriers (sampling time offset). Both
//!    change from frame to frame at random and would swamp any variance.
//!    The standard cleaning is a least-squares line across the subcarriers,
//!    subtracted; what is left is the multipath's own shape.
//!    [`CsiFrame::phases`] does that in integer arithmetic.
//! 3. [`PhaseDetector::push`] keeps the last `W` sanitised phase vectors and
//!    computes, per subcarrier, the **circular variance** over the window:
//!    `1 − |mean of the unit vectors|`, from carried cosine and sine sums
//!    and a 257-entry quarter-wave sine table. Averaged over the
//!    subcarriers, in **parts per million**, it is the phase twin of the
//!    amplitude wander, and the same hysteresis turns it into a [`Verdict`].
//!
//! ppm and not permille because the signal is small. On the ledger's
//! captures an empty room's phase residual jitters by about a degree -- a
//! circular variance near 200 ppm -- and a person walking reads a few
//! hundred to 1 500 ppm. In permille that is the integers 0, 1 and 2.
//!
//! Circular variance rather than a plain standard deviation because the
//! residual is still an angle: a subcarrier hovering around ±half a turn
//! would read as maximally spread to a linear statistic while being
//! perfectly still. Bounded by construction in `[0, 1]`, so the permille is
//! honest at both ends.
//!
//! # What the ledger says about it
//!
//! Derived and checked on the same two ESP32-C6 captures as the amplitude
//! detector (`tests/csi_capture.rs`), against an independent float replica
//! (`tools/csi_phase_oracle.py`). The numbers are in `docs/LEDGER.md`; the
//! thresholds in [`Config::phase_default`] come from them and nowhere else.

